export function lastSyllable(noun: string) {
  const characters = [...noun.trim().normalize("NFC")];
  const last = characters.at(-1);
  if (!last) return null;
  const offset = last.charCodeAt(0) - 0xac00;
  if (offset < 0 || offset >= 11172) return null;
  return { stem: characters.slice(0, -1).join(""), last, batchim: offset % 28 };
}

